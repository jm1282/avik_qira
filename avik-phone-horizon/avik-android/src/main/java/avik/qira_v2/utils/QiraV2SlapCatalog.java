    public static final class SlapString {
        private final String stringId;
        private final String messageId;
        private final String source;
        private final String atm;
        private final String pathPrefix;
        private final String composeModule;
        private final String composeResourceFile;

        private SlapString(
                String stringId,
                String messageId,
                String source,
                String atm,
                String pathPrefix,
                String composeModule,
                String composeResourceFile) {
            this.stringId = stringId;
            this.messageId = messageId;
            this.source = source;
            this.atm = atm;
            this.pathPrefix = pathPrefix;
            this.composeModule = composeModule;
            this.composeResourceFile = composeResourceFile;
        }

        public String getStringId() {
            return stringId;
        }

        public String getMessageId() {
            return messageId;
        }

        public String getSource() {
            return source;
        }

        public String getAtm() {
            return atm;
        }

        public String getPathPrefix() {
            return pathPrefix;
        }

        public String getComposeModule() {
            return composeModule;
        }

        public String getComposeResourceFile() {
            return composeResourceFile;
        }

        public String toLogString() {
            return "stringId=" + stringId
                    + ", messageId=" + messageId
                    + ", source='" + source + "'"
                    + ", atm=" + atm
                    + ", pathPrefix=" + pathPrefix
                    + ", composeModule=" + composeModule
                    + ", composeResourceFile=" + composeResourceFile;
        }
    }
