    private boolean hasFeatureBackIconByDescription() {
        int width = mDevice.getDisplayWidth();
        int height = mDevice.getDisplayHeight();
        for (UiObject2 object : mDevice.findObjects(By.pkg(mConfig.getPackageName()))) {
            try {
                String desc = object.getContentDescription();
                if (desc == null || desc.trim().isEmpty()) {
                    continue;
                }
                String normalizedDesc = QiraStrings.stripBidiControls(desc)
                        .trim()
                        .toLowerCase(Locale.US);
                if (!isBackControlDescription(normalizedDesc)) {
                    continue;
                }
                if (isTopLeftIconBounds(object.getVisibleBounds(), width, height)
                        || isFeatureBackIconBounds(object.getVisibleBounds(), width, height)) {
                    return true;
                }
            } catch (StaleObjectException ignored) {
                // Node recycled while scanning.
            }
        }
        return false;
    }

    private boolean isCreatorHomeVisibleByGeometry() {
        List<UiObject2> candidates = findCreatorFeatureTileCandidates();
        if (candidates.size() < FEATURE_TILES.length) {
            return false;
        }

        int width = mDevice.getDisplayWidth();
        int left = 0;
        int middle = 0;
        int right = 0;
        int topRow = 0;
        int bottomRow = 0;
        int height = mDevice.getDisplayHeight();
        for (UiObject2 candidate : candidates) {
            try {
                Rect bounds = candidate.getVisibleBounds();
                int cx = bounds.centerX();
                if (cx < (width * 35) / 100) {
                    left++;
                } else if (cx > (width * 65) / 100) {
                    right++;
                } else {
                    middle++;
                }
                if (bounds.centerY() < (height * 34) / 100) {
                    topRow++;
                } else {
                    bottomRow++;
                }
            } catch (StaleObjectException ignored) {
                // Node recycled during column tally.
            }
        }
        return left >= 2 && middle >= 2 && right >= 2
                && topRow >= 3 && bottomRow >= 3;
    }

    private List<UiObject2> findCreatorFeatureTileCandidates() {
        int width = mDevice.getDisplayWidth();
        int height = mDevice.getDisplayHeight();
        List<UiObject2> candidates = new ArrayList<>();

        for (UiObject2 object : mDevice.findObjects(
                By.pkg(mConfig.getPackageName()).clickable(true))) {
            try {
                Rect bounds = object.getVisibleBounds();
                if (bounds == null || bounds.isEmpty()) {
                    continue;
                }
                if (bounds.top < (height * 16) / 100 || bounds.bottom > (height * 50) / 100) {
                    continue;
                }
                if (bounds.width() < (width * 22) / 100 || bounds.width() > (width * 40) / 100) {
                    continue;
                }
                if (bounds.height() < (height * 8) / 100 || bounds.height() > (height * 18) / 100) {
                    continue;
                }
                candidates.add(object);
            } catch (StaleObjectException ignored) {
                // Node recycled while scanning.
            }
        }

        // Reading order: top-to-bottom rows, then leading-edge first within a
        // row. Under RTL the Creator grid mirrors (first tile is top-right), so
        // within a row we sort right-to-left; LTR is unchanged (byte-identical
        // for en-XM). featureTileIndex() is a logical reading-order index, so
        // this keeps grid-position taps mapped to the correct feature tile in
        // both directions.
        final boolean rtl = isCurrentLocaleRtlLayout();
        Collections.sort(candidates, new Comparator<UiObject2>() {
            @Override
            public int compare(UiObject2 a, UiObject2 b) {
                Rect ab = a.getVisibleBounds();
                Rect bb = b.getVisibleBounds();
                int dy = ab.top - bb.top;
                if (Math.abs(dy) > 40) {
                    return dy;
                }
                return rtl ? (bb.left - ab.left) : (ab.left - bb.left);
            }
        });
        return candidates;
    }

    /**
     * Fallback tile locator: scans all clickable Compose nodes in the package
     * and returns the one whose visible bounds contain the label. This handles
     * cases where the label's immediate ancestors are not marked clickable.
     */
    private UiObject2 findNearestClickableTile(UiObject2 label, String featureLabel) {
        Rect labelBounds;
        try {
            labelBounds = label.getVisibleBounds();
        } catch (StaleObjectException stale) {
            return null;
        }
        if (labelBounds == null || labelBounds.isEmpty()) {
            return null;
        }
        List<UiObject2> clickables =
                mDevice.findObjects(By.pkg(mConfig.getPackageName()).clickable(true));
        UiObject2 best = null;
        int bestArea = Integer.MAX_VALUE;
        for (UiObject2 obj : clickables) {
            try {
                Rect b = obj.getVisibleBounds();
                if (b == null || b.isEmpty()) {
                    continue;
                }
                if (!b.contains(labelBounds.centerX(), labelBounds.centerY())) {
                    continue;
                }
                int area = b.width() * b.height();
                if (area > 0 && area < bestArea) {
                    bestArea = area;
                    best = obj;
                }
            } catch (StaleObjectException ignored) {
                // Node went away while we were scanning; skip it.
            }
        }
        if (best != null) {
            CREATOR_ZONE_LOGGER.info("Creator Zone: tile '" + featureLabel
                    + "' resolved via clickable-ancestor fallback.");
        }
        return best;
    }

    private UiObject2 findTopLeftBackControlByDescription() {
        UiObject2 best = null;
        int bestScore = Integer.MAX_VALUE;
        int width = mDevice.getDisplayWidth();
        int height = mDevice.getDisplayHeight();
        for (UiObject2 object : mDevice.findObjects(By.pkg(mConfig.getPackageName()))) {
            try {
                String desc = object.getContentDescription();
                if (desc == null || desc.trim().isEmpty()) {
                    continue;
                }
                String normalizedDesc = QiraStrings.stripBidiControls(desc)
                        .trim()
                        .toLowerCase(Locale.US);
                if (!isBackControlDescription(normalizedDesc)) {
                    continue;
                }
                Rect bounds = object.getVisibleBounds();
                if (!isTopLeftIconBounds(bounds, width, height)
                        && !isFeatureBackIconBounds(bounds, width, height)) {
                    continue;
                }
                UiObject2 clickable = findClickableAncestor(object);
                UiObject2 target = clickable != null ? clickable : object;
                Rect clickableBounds = target.getVisibleBounds();
                if (!isTopLeftBackBounds(clickableBounds, width, height)
                        && !isTopLeftIconBounds(clickableBounds, width, height)
                        && !isFeatureBackIconBounds(clickableBounds, width, height)) {
                    continue;
                }
                int score = scoreTopLeftCandidate(clickableBounds) - 40;
                if (score < bestScore) {
                    bestScore = score;
                    best = target;
                }
            } catch (StaleObjectException ignored) {
                // Node recycled while scanning.
            }
        }
        return best;
    }

    private boolean isBackControlDescription(String desc) {
        return desc.contains("back")
                || desc.contains("arrow back")
                || desc.contains("navigate up")
                || desc.contains("up button");
    }

    private UiObject2 findTopLeftBackControlByGeometry() {
        UiObject2 best = null;
        int bestScore = Integer.MAX_VALUE;
        int width = mDevice.getDisplayWidth();
        int height = mDevice.getDisplayHeight();
        for (UiObject2 object : mDevice.findObjects(
                By.pkg(mConfig.getPackageName()).clickable(true))) {
            try {
                Rect bounds = object.getVisibleBounds();
                if (!isTopLeftBackBounds(bounds, width, height)) {
                    continue;
                }
                int score = scoreTopLeftCandidate(bounds);
                if (score < bestScore) {
                    bestScore = score;
                    best = object;
                }
            } catch (StaleObjectException ignored) {
                // Node recycled while scanning.
            }
        }
        return best;
    }

