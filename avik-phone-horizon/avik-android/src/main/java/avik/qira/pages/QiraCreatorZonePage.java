    public boolean waitForInformationDialog(long timeoutMs) throws Exception {
        // Poll the strict dialog detector rather than matching the bare
        // "Information" label. On the current build the composer's daily-quota
        // affordance is an ImageView whose content-desc is literally
        // "Information", so a plain label match returned true even when only the
        // chip (not the dialog) was on screen - causing QuotaInfoPopup to capture
        // the composer and a spurious geometry "dismiss" to focus the prompt
        // field. isInformationDialogVisible() requires the dialog's Got-It action
        // plus its overlay (or the centered title), so it only fires for the real
        // dialog.
        long deadline = System.currentTimeMillis() + timeoutMs;
        while (System.currentTimeMillis() < deadline) {
            if (isInformationDialogVisible()) {
                return true;
            }
            mUtils.sleep(150L);
        }
        return false;
    }

    /** Dismisses the Information dialog via its "Got It" button. */
    public boolean tapGotIt() throws Exception {
        UiObject2 gotItByLabel = waitForExactTextOrDescription(1000L, INFORMATION_GOT_IT_LABELS);
        if (gotItByLabel != null && shellClickObject(gotItByLabel)) {
            CREATOR_ZONE_LOGGER.info("Creator Zone: information dialog dismissed by label.");
            mUtils.sleep(1200L);
            return true;
        }
        UiObject2 action = findCenteredDialogActionByGeometry();
        if (action == null) {
            action = findCenteredDialogActionByTextGeometry();
        }
        if (action == null) {
            return false;
        }
        if (!shellClickObject(action)) {
            clickObject(action);
        }
        CREATOR_ZONE_LOGGER.info("Creator Zone: information dialog dismissed by geometry.");
        mUtils.sleep(1200L);
        return true;
    }

    public boolean dismissInformationDialogIfVisible() throws Exception {
        if (!isInformationDialogVisible() && !hasCreatorInformationDialogOverlay()) {
            return false;
        }
        boolean dismissed = tapGotIt();
        if (dismissed) {
            CREATOR_ZONE_LOGGER.info("Creator Zone: quota information popup dismissed.");
        }
        return dismissed;
    }

    /**
     * Taps the "N/M left today" daily-quota chip that lives next to the
     * aspect-ratio toggle in the composer surfaces. The chip acts as a button
     * that re-opens the "Information" (daily image quota) dialog. Returns
     * false when no such chip is visible.
     */
    public boolean tapDailyQuotaChip() throws Exception {
        // Primary path: the composer quota row exposes a dedicated info affordance
        // with a stable content-desc "Information" (verified live, en-XM). Tapping
        // it re-opens the daily-quota dialog. This is preferred over the geometry
        // heuristics below because on the current build the info icon overlaps the
        // (very wide) quota-text bounds, so the "action to the right of the chip"
        // heuristic in findDailyQuotaInfoActionNearChip skips it.
        UiObject2 infoIcon = findComposerQuotaInfoIcon();
        if (infoIcon != null) {
            clickObject(infoIcon);
            return true;
        }

        UiObject2 chip = mDevice.findObject(
                By.pkg(mConfig.getPackageName()).descContains(DAILY_QUOTA_SUFFIX));
        if (chip == null) {
            chip = mDevice.findObject(
                By.pkg(mConfig.getPackageName()).textContains(DAILY_QUOTA_SUFFIX));
        }
        if (chip == null) {
            chip = findDailyQuotaChipByPattern();
            if (chip == null) {
                return false;
            }
        }
        UiObject2 quotaAction = findDailyQuotaInfoActionNearChip(chip);
        if (quotaAction != null) {
            clickObject(quotaAction);
            return true;
        }

        UiObject2 clickable = findClickableAncestor(chip);
        if (clickable != null) {
            Rect clickableBounds = safeBounds(clickable);
            if (isLikelyDailyQuotaActionBounds(clickableBounds)) {
                clickObject(clickable);
                return true;
            }
        }

        // Last-resort tap: hit the right side of the chip row where the info
        // affordance usually lives, instead of tapping the text label itself.
        Rect chipBounds = safeBounds(chip);
        if (chipBounds == null || chipBounds.isEmpty()) {
            return false;
        }
        int width = mDevice.getDisplayWidth();
        int x = Math.min(width - 48, chipBounds.right - 8);
        int y = chipBounds.centerY();
        mDevice.click(x, y);
        settle();
        return true;
    }

