    /** Advances the onboarding carousel. Returns false if no Next control is visible. */
    public boolean tapNext() throws Exception {
        UiObject2 nextByLabel = waitForExactTextOrDescription(1000L, ONBOARDING_NEXT_LABELS);
        if (nextByLabel != null && shellClickObject(nextByLabel)) {
            CREATOR_ZONE_LOGGER.info("Creator Zone: onboarding Next clicked by label.");
            mUtils.sleep(1500L);
            return true;
        }
        UiObject2 next = findCreatorOnboardingPrimaryActionByGeometry();
        if (next == null) {
            return false;
        }
        if (!shellClickObject(next)) {
            clickObject(next);
        }
        CREATOR_ZONE_LOGGER.info("Creator Zone: onboarding Next clicked by geometry.");
        mUtils.sleep(1500L);
        return true;
    }

