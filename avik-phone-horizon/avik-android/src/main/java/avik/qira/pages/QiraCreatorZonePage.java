    /**
     * Handles the Android runtime photos/videos (and other) permission
     * dialogs that Create avatar / Edit image / Style Sync may raise the first
     * time they are opened. <strong>Always grants full access</strong>: taps
     * "Allow all" when present, then "Allow" / "While using the app", and
     * finally "Only this time" as a last resort. Deliberately avoids the
     * "Allow limited access" / "Don't allow" buttons so the script always runs
     * with full read access (per the test requirements). Returns true when a
     * prompt was dismissed.
     */
    public boolean acceptPhotosPermissionIfPresent(long timeoutMs) throws Exception {
        long deadline = System.currentTimeMillis() + timeoutMs;
        int dismissed = 0;
        while (System.currentTimeMillis() < deadline) {
            if (!isPermissionPromptVisible()) {
                if (dismissed > 0) {
                    return true;
                }
                mUtils.sleep(200L);
                continue;
            }
            // Allow all grants read access to every photo/video so the rest of
            // the Create avatar / Edit image / Style Sync flows can pick any
            // item without re-prompting.
            if (clickByResource(
                    "com.android.permissioncontroller:id/permission_allow_all_button",
                    "com.android.permissioncontroller:id/permission_allow_foreground_only_button",
                    "com.android.permissioncontroller:id/permission_allow_button",
                    "com.android.permissioncontroller:id/permission_allow_one_time_button")) {
                dismissed++;
                settle();
                mUtils.sleep(500L);
                continue;
            }
            if (clickByExactTextOrDescriptionNoAuto(
                    "Allow all",
                    "Allow",
                    "While using the app",
                    "Only this time")) {
                dismissed++;
                settle();
                mUtils.sleep(500L);
                continue;
            }
            mUtils.sleep(250L);
        }
        return dismissed > 0;
    }

