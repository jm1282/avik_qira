    /**
     * Taps the given feature tile on the Creator Zone home. The tile itself is
     * a clickable Compose view that contains a non-clickable TextView with the
     * feature's visible label; we locate the label and click its nearest
     * clickable ancestor so the card receives the tap rather than the label.
     */
    public boolean tapFeatureTile(String featureLabel) throws Exception {
        UiObject2 label = findFeatureTileLabelByResourceId(featureLabel);
        if (label == null) {
            label = findFeatureTileLabel(featureLabel);
        }
        if (label == null) {
            // On some locale/layout combinations the 2nd row is slightly below
            // the initial viewport after returning from Scribble/Editor screens.
            // Do one deterministic upward swipe and retry stable selectors.
            swipeCreatorHomeGridUp();
            label = findFeatureTileLabelByResourceId(featureLabel);
            if (label == null) {
                label = findFeatureTileLabel(featureLabel);
            }
        }

        if (label != null) {
            UiObject2 clickable = findClickableAncestor(label);
            if (clickable == null) {
                clickable = findNearestClickableTile(label, featureLabel);
            }
            if (clickable != null) {
                clickObject(clickable);
                CREATOR_ZONE_LOGGER.info("Creator Zone: tile '" + featureLabel
                        + "' clicked through its resource-backed label ancestor.");
                return true;
            }
        }

        if (!allowGeometryFallbacks) {
            CREATOR_ZONE_LOGGER.info("Creator Zone: stable tile selector unavailable for '"
                    + featureLabel + "'; geometry fallback is disabled.");
            return false;
        }

        UiObject2 geometryTile = findFeatureTileByGeometry(featureLabel);
        if (geometryTile == null) {
            return false;
        }
        shellClickObject(geometryTile);
        CREATOR_ZONE_LOGGER.info("Creator Zone: tile '" + featureLabel
                + "' clicked by legacy Creator-grid geometry fallback.");
        return true;
    }

    public boolean tapFeatureTileByGridPosition(String featureLabel) throws Exception {
        if (!allowGeometryFallbacks) {
            return tapFeatureTile(featureLabel);
        }
        int targetIndex = featureTileIndex(featureLabel);
        if (targetIndex < 0) {
            return false;
        }

        List<UiObject2> candidates = findCreatorFeatureTileCandidates();
        if (targetIndex < candidates.size()) {
            Rect bounds = safeBounds(candidates.get(targetIndex));
            if (bounds != null && !bounds.isEmpty()) {
                shellClickObject(candidates.get(targetIndex));
                CREATOR_ZONE_LOGGER.info("Creator Zone: tile '" + featureLabel
                        + "' clicked by grid position.");
                return true;
            }
        }

        CREATOR_ZONE_LOGGER.info("Creator Zone: grid position for tile '" + featureLabel
                + "' was unavailable; refusing coordinate fallback.");
        return false;
    }

    private UiObject2 findFeatureTileLabelByResourceId(String featureLabel) {
        int targetIndex = featureTileIndex(featureLabel);
        if (targetIndex < 0 || targetIndex >= FEATURE_TILE_RESOURCE_IDS.length) {
            return null;
        }
        UiObject2 best = null;
        int bestScore = Integer.MAX_VALUE;
        for (String localizedLabel : localizeStringIds(
                FEATURE_TILE_RESOURCE_IDS[targetIndex])) {
            UiObject2 candidate = bestFeatureTileLabelForSelector(
                    By.pkg(mConfig.getPackageName()).desc(
                            exactPatternForLabel(localizedLabel)),
                    targetIndex);
            int score = scoreFeatureTileLabel(candidate, targetIndex);
            if (candidate != null && score < bestScore) {
                best = candidate;
                bestScore = score;
            }
            candidate = bestFeatureTileLabelForSelector(
                    By.pkg(mConfig.getPackageName()).text(
                            exactPatternForLabel(localizedLabel)),
                    targetIndex);
            score = scoreFeatureTileLabel(candidate, targetIndex);
            if (candidate != null && score < bestScore) {
                best = candidate;
                bestScore = score;
            }
        }
        return best;
    }

    private void swipeCreatorHomeGridUp() {
        int width = mDevice.getDisplayWidth();
        int height = mDevice.getDisplayHeight();
        int x = width / 2;
        int startY = (height * 72) / 100;
        int endY = (height * 30) / 100;
        mDevice.swipe(x, startY, x, endY, 28);
    }

    /**
     * Locale-safe fallback used when a feature label cannot be matched by text
     * or content-description. Creator Zone renders feature cards in a stable
     * 3x2 grid order matching {@link #FEATURE_TILES}.
     */
    private UiObject2 findFeatureTileByGeometry(String featureLabel) {
        int targetIndex = featureTileIndex(featureLabel);
        if (targetIndex < 0) {
            return null;
        }

        List<UiObject2> candidates = findCreatorFeatureTileCandidates();
        if (targetIndex >= candidates.size()) {
            return null;
        }
        CREATOR_ZONE_LOGGER.info("Creator Zone: tile '" + featureLabel
                + "' resolved via geometry fallback.");
        return candidates.get(targetIndex);
    }

    private int featureTileIndex(String featureLabel) {
        for (int i = 0; i < FEATURE_TILES.length; i++) {
            if (FEATURE_TILES[i].equals(featureLabel)) {
                return i;
            }
        }
        return -1;
    }

    private UiObject2 findFeatureTileLabel(String featureLabel) {
        int targetIndex = featureTileIndex(featureLabel);
        UiObject2 best = null;
        int bestScore = Integer.MAX_VALUE;
        for (String localizedLabel : localizeLabels(featureLabel)) {
            UiObject2 candidate = bestFeatureTileLabelForSelector(
                    By.pkg(mConfig.getPackageName()).desc(patternForLabel(localizedLabel)),
                    targetIndex);
            int score = scoreFeatureTileLabel(candidate, targetIndex);
            if (candidate != null && score < bestScore) {
                bestScore = score;
                best = candidate;
            }

            candidate = bestFeatureTileLabelForSelector(
                    By.pkg(mConfig.getPackageName()).text(patternForLabel(localizedLabel)),
                    targetIndex);
            score = scoreFeatureTileLabel(candidate, targetIndex);
            if (candidate != null && score < bestScore) {
                bestScore = score;
                best = candidate;
            }
        }
        return best;
    }

    private UiObject2 bestFeatureTileLabelForSelector(
            androidx.test.uiautomator.BySelector selector,
            int targetIndex) {
        UiObject2 best = null;
        int bestScore = Integer.MAX_VALUE;
        for (UiObject2 object : mDevice.findObjects(selector)) {
            int score = scoreFeatureTileLabel(object, targetIndex);
            if (score < bestScore) {
                bestScore = score;
                best = object;
            }
        }
        return best;
    }

    private int scoreFeatureTileLabel(UiObject2 object, int targetIndex) {
        if (object == null || targetIndex < 0) {
            return Integer.MAX_VALUE;
        }
        Rect bounds = safeBounds(object);
        if (!isFeatureGridLabelBounds(bounds)) {
            return Integer.MAX_VALUE;
        }
        int width = mDevice.getDisplayWidth();
        int height = mDevice.getDisplayHeight();
        int[] xPercent = {18, 50, 82};
        int targetX = (width * xPercent[targetIndex % 3]) / 100;
        int targetY = (height * (targetIndex < 3 ? 26 : 40)) / 100;
        return Math.abs(bounds.centerX() - targetX) + Math.abs(bounds.centerY() - targetY);
    }

    private boolean isFeatureGridLabelBounds(Rect bounds) {
        if (bounds == null || bounds.isEmpty()) {
            return false;
        }
        int width = mDevice.getDisplayWidth();
        int height = mDevice.getDisplayHeight();
        return bounds.left >= 0
                && bounds.right <= width
                && bounds.top >= (height * 12) / 100
                && bounds.bottom <= (height * 48) / 100
                && bounds.width() >= (width * 5) / 100
                && bounds.height() >= (height * 1) / 100;
    }

