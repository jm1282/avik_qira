    private boolean isPhotoPickerPackage(String packageName) {
        if (packageName == null || packageName.isEmpty()) {
            return false;
        }
        for (String candidate : PHOTO_PICKER_PACKAGES) {
            if (candidate.equals(packageName)) {
                return true;
            }
        }
        return packageName.contains("photopicker")
                || packageName.contains("providers.media");
    }

    private String resolvePhotoPickerPackage() {
        String currentPackage = mDevice.getCurrentPackageName();
        if (isPhotoPickerPackage(currentPackage)) {
            return currentPackage;
        }
        for (String candidate : PHOTO_PICKER_PACKAGES) {
            UiObject2 object = mDevice.findObject(By.pkg(candidate));
            if (object != null) {
                return candidate;
            }
        }
        return null;
    }

