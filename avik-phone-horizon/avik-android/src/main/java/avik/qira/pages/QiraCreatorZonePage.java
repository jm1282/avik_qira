    private UiObject2 findScribbleExitConfirmByGeometry() {
        int width = mDevice.getDisplayWidth();
        int height = mDevice.getDisplayHeight();
        List<UiObject2> candidates = new ArrayList<>();

        for (UiObject2 object : mDevice.findObjects(
                By.pkg(mConfig.getPackageName()).clickable(true))) {
            try {
                Rect bounds = object.getVisibleBounds();
                if (bounds == null || bounds.isEmpty()) {
                    continue;
                }
                if (bounds.top < (height * 36) / 100 || bounds.bottom > (height * 80) / 100) {
                    continue;
                }
                if (bounds.left < (width * 12) / 100 || bounds.right > (width * 90) / 100) {
                    continue;
                }
                if (bounds.width() < (width * 14) / 100 || bounds.width() > (width * 40) / 100) {
                    continue;
                }
                if (bounds.height() < (height * 3) / 100 || bounds.height() > (height * 12) / 100) {
                    continue;
                }
                candidates.add(object);
            } catch (StaleObjectException ignored) {
                // Node recycled while scanning.
            }
        }

        UiObject2 best = null;
        int bestX = Integer.MIN_VALUE;
        int yTolerance = (height * 6) / 100;
        int minHorizontalSeparation = (width * 12) / 100;
        for (UiObject2 candidate : candidates) {
            Rect cb;
            try {
                cb = candidate.getVisibleBounds();
            } catch (StaleObjectException stale) {
                continue;
            }
            if (cb == null || cb.isEmpty()) {
                continue;
            }
            boolean hasSibling = false;
            for (UiObject2 other : candidates) {
                if (other == candidate) {
                    continue;
                }
                Rect ob;
                try {
                    ob = other.getVisibleBounds();
                } catch (StaleObjectException stale) {
                    continue;
                }
                if (ob == null || ob.isEmpty()) {
                    continue;
                }
                if (Math.abs(cb.centerY() - ob.centerY()) > yTolerance) {
                    continue;
                }
                if (Math.abs(cb.centerX() - ob.centerX()) < minHorizontalSeparation) {
                    continue;
                }
                hasSibling = true;
                break;
            }
            if (!hasSibling) {
                continue;
            }
            if (cb.centerX() > bestX) {
                bestX = cb.centerX();
                best = candidate;
            }
        }
        return best;
    }

