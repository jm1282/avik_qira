    /**
     * Waits until any recognizable Creator Zone surface is visible and returns
     * this page. This is intentionally tolerant: callers that navigate to
     * Creator Zone from the home tile grid may land on the onboarding
     * carousel, the Information (daily image quota) dialog, or the Creator
     * Zone home grid depending on whether the surface has been visited
     * before. Returning on any of those three gives callers a consistent
     * "loaded" signal without forcing them to know the current state.
     *
     * <p>Throws {@link IllegalStateException} if no known surface appears
     * within {@link #DEFAULT_TIMEOUT_MS}.
     */
    public QiraCreatorZonePage waitForLoaded() throws Exception {
        long deadline = System.currentTimeMillis() + DEFAULT_TIMEOUT_MS;
        while (System.currentTimeMillis() < deadline) {
            if (isCreatorHomeVisible()
                    || isOnboardingPage1Visible()
                    || isOnboardingPage2Visible()
                    || isOnboardingPage3Visible()
                    || isInformationDialogVisible()
                    || isConfirmUsageDialogVisible()) {
                return this;
            }
            Thread.sleep(200L);
        }
        throw new IllegalStateException("Unable to detect the Creator Zone surface");
    }

