    /**
     * Scrolls the Create image horizontal style carousel by one "page". The
     * carousel is discovered by finding the scrollable container whose child
     * labels match known style names.
     */
    public boolean scrollStyleCarousel(boolean forward) throws Exception {
        // Rule-set #1: desc before text. Anchor the horizontal swipe on any
        // matching style tile regardless of locale; content-desc wins first
        // in findByExactTextOrDescription.
        UiObject2 anchor = findByExactTextOrDescription("Abstract");
        if (anchor == null) {
            for (String s : CREATE_IMAGE_STYLE_LABELS) {
                anchor = findByExactTextOrDescription(s);
                if (anchor != null) {
                    break;
                }
            }
        }
        if (anchor == null) {
            anchor = findCreateImageStyleAnchorByGeometry();
            if (anchor == null) {
                return false;
            }
        }
        Rect b;
        try {
            b = anchor.getVisibleBounds();
        } catch (StaleObjectException stale) {
            return false;
        }
        if (b == null || b.isEmpty()) {
            return false;
        }
        int height = mDevice.getDisplayHeight();
        if (b.top < (height * 50) / 100 || b.bottom > (height * 78) / 100) {
            // Guard against accidental anchor matches on the Creator home tile grid.
            UiObject2 geometryAnchor = findCreateImageStyleAnchorByGeometry();
            if (geometryAnchor == null) {
                return false;
            }
            b = safeBounds(geometryAnchor);
            if (b == null || b.isEmpty()) {
                return false;
            }
        }
        int y = b.centerY();
        int w = mDevice.getDisplayWidth();
        int left = Math.max(200, w / 10);
        int right = w - left;
        if (forward) {
            mDevice.swipe(right, y, left, y, 25);
        } else {
            mDevice.swipe(left, y, right, y, 25);
        }
        settle();
        return true;
    }

    public boolean selectCreateImageStyle(String style) throws Exception {
        if (style == null || style.trim().isEmpty()) {
            return false;
        }
        // Rewind the style carousel to the start first: a prior _Styles scroll can
        // leave the rail advanced to a later page (e.g. Minimalist/Pop Art/...),
        // and searching only forward from there would scroll past early styles
        // like Fantasy instead of toward them.
        for (int i = 0; i < 5; i++) {
            if (!scrollStyleCarousel(false)) {
                break;
            }
            mUtils.sleep(250L);
        }
        for (int attempt = 0; attempt < 6; attempt++) {
            UiObject2 option = findByExactTextOrDescription(style);
            if (option != null) {
                // The style label and its clickable thumbnail are SIBLINGS - the
                // thumbnail sits directly above the label, so
                // findClickableAncestor(label) walks past the chip to the whole
                // carousel and the tap does not select the style. Prefer the
                // clickable thumbnail aligned with the label's column.
                UiObject2 chip = findStyleChipThumbnailForLabel(option);
                if (chip != null) {
                    clickObject(chip);
                    return true;
                }
                UiObject2 clickable = findClickableAncestor(option);
                clickObject(clickable != null ? clickable : option);
                return true;
            }
            if (!scrollStyleCarousel(true)) {
                break;
            }
            mUtils.sleep(400L);
        }
        return false;
    }

    /**
     * Finds the clickable style-chip thumbnail that belongs to a style label.
     * The composer renders each style as a clickable image with the style label
     * as a separate sibling text node directly beneath it, so we select the
     * nearest clickable node that shares the label's horizontal column and sits
     * just above it. Locale-independent (keys off the label geometry, not the
     * localized style description).
     */
    private UiObject2 findStyleChipThumbnailForLabel(UiObject2 label) {
        Rect lb = safeBounds(label);
        if (lb == null || lb.isEmpty()) {
            return null;
        }
        int labelCx = lb.centerX();
        int maxGap = (mDevice.getDisplayHeight() * 6) / 100;
        UiObject2 best = null;
        int bestDy = Integer.MAX_VALUE;
        for (UiObject2 object : mDevice.findObjects(
                By.pkg(mConfig.getPackageName()).clickable(true))) {
            Rect b = safeBounds(object);
            if (b == null || b.isEmpty()) {
                continue;
            }
            if (labelCx < b.left || labelCx > b.right) {
                continue;
            }
            if (b.bottom > lb.top + 8) {
                continue;
            }
            int dy = lb.top - b.bottom;
            if (dy < 0 || dy > maxGap) {
                continue;
            }
            if (dy < bestDy) {
                bestDy = dy;
                best = object;
            }
        }
        return best;
    }

