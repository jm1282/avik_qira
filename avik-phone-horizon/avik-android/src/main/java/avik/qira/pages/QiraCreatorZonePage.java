    public boolean isHomeTileVisible() {
        return hasTextOrDescription(HOME_CREATOR_TILE_LABELS)
                || findCreatorTileByGeometry() != null;
    }

    /**
     * Taps the Creator Zone tile on the Qira home surface. We intentionally
     * click the deepest clickable ancestor so the whole card is activated
     * (the inner label TextView is not itself clickable).
     */
    public void tapCreatorZoneTile() throws Exception {
        UiObject2 label = findByExactTextOrDescription(TILE_CREATOR_ZONE);
        if (label == null) {
            UiObject2 fallback = findCreatorTileByGeometry();
            if (fallback == null) {
                throw new IllegalStateException(
                        "Unable to locate the Creator Zone tile on the Qira home");
            }
            clickObject(fallback);
            return;
        }
        UiObject2 clickable = findClickableAncestor(label);
        clickObject(clickable != null ? clickable : label);
    }

    /**
     * Discover-home fallback for localized builds where the Creator Zone card
     * does not expose an English text/content-desc match. Creator Zone is the
     * top-most left-column card in the 2-column Discover layout.
     */
    private UiObject2 findCreatorTileByGeometry() {
        List<UiObject2> cards = findDiscoverCardsByGeometry();
        if (cards.isEmpty()) {
            return null;
        }
        int width = mDevice.getDisplayWidth();
        UiObject2 best = null;
        int bestTop = Integer.MAX_VALUE;
        for (UiObject2 card : cards) {
            try {
                Rect bounds = card.getVisibleBounds();
                if (bounds.centerX() >= (width * 45) / 100) {
                    continue;
                }
                if (bounds.top < bestTop) {
                    bestTop = bounds.top;
                    best = card;
                }
            } catch (StaleObjectException ignored) {
                // Node recycled while scanning.
            }
        }
        return best;
    }

    private List<UiObject2> findDiscoverCardsByGeometry() {
        int width = mDevice.getDisplayWidth();
        int height = mDevice.getDisplayHeight();
        List<UiObject2> cards = new ArrayList<>();

        int leftColumn = 0;
        int rightColumn = 0;
        int middleColumn = 0;

        for (UiObject2 object : mDevice.findObjects(
                By.pkg(mConfig.getPackageName()).clickable(true))) {
            try {
                Rect bounds = object.getVisibleBounds();
                if (bounds == null || bounds.isEmpty()) {
                    continue;
                }
                if (bounds.top < (height * 10) / 100 || bounds.bottom > (height * 93) / 100) {
                    continue;
                }
                if (bounds.width() < (width * 18) / 100 || bounds.width() > (width * 56) / 100) {
                    continue;
                }
                if (bounds.height() < (height * 9) / 100 || bounds.height() > (height * 34) / 100) {
                    continue;
                }
                cards.add(object);
                int cx = bounds.centerX();
                if (cx < (width * 45) / 100) {
                    leftColumn++;
                } else if (cx > (width * 55) / 100) {
                    rightColumn++;
                } else {
                    middleColumn++;
                }
            } catch (StaleObjectException ignored) {
                // Node recycled while scanning.
            }
        }

        if (cards.size() < 4 || leftColumn < 2 || rightColumn < 2 || middleColumn > 1) {
            return new ArrayList<>();
        }

        Collections.sort(cards, new Comparator<UiObject2>() {
            @Override
            public int compare(UiObject2 a, UiObject2 b) {
                Rect ab = a.getVisibleBounds();
                Rect bb = b.getVisibleBounds();
                int dy = ab.top - bb.top;
                if (Math.abs(dy) > 40) {
                    return dy;
                }
                return ab.left - bb.left;
            }
        });
        return cards;
    }

